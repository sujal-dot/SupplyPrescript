"""
SupplyPrescript — Predictions API Router
========================================
Exposes endpoints for running machine learning inference on shipment delay risk.
Includes production Day 9 endpoint (POST /api/predict) with database feature resolution
and backward-compatible Day 7 endpoint (POST /api/predictions/shipment-delay).
"""

import logging
from fastapi import APIRouter, Depends, status
from sqlalchemy.orm import Session

from app.database.connection import get_db
from app.schemas.prediction import (
    PredictRequest,
    PredictResponse,
    ShipmentPredictionRequest,
    ShipmentPredictionResult,
)
from app.services.prediction_service import PredictionService

logger = logging.getLogger("app.api.routes.predictions")

router = APIRouter(tags=["Predictions"])


@router.post(
    "/api/predict",
    response_model=PredictResponse,
    status_code=status.HTTP_200_OK,
    summary="Predict shipment delay risk, probability, and duration",
    description=(
        "Accepts shipment and scenario details, queries PostgreSQL for authoritative supplier "
        "and product features, invokes active registered ML models (v1.0 XGBoost classifier and regressor), "
        "and returns delay probability, predicted delay duration in days, and risk classification."
    ),
    responses={
        200: {
            "description": "Successful prediction generated by active ML models.",
            "content": {
                "application/json": {
                    "example": {
                        "delay_probability": 0.87,
                        "predicted_delay_days": 14.0,
                        "risk": "HIGH",
                        "model_version": "v1.0",
                        "prediction_id": "PRED-1A2B3C4D5E6F",
                        "prediction_timestamp": "2026-10-12T10:00:00Z"
                    }
                }
            },
        },
        400: {"description": "Invalid business input or required feature data missing."},
        404: {"description": "Referenced supplier or product not found."},
        422: {"description": "Request validation error or target leakage attempt."},
        503: {"description": "Predictive model artifacts are unavailable."},
        500: {"description": "Internal server error occurred."},
    },
)
def predict(
    request: PredictRequest,
    db: Session = Depends(get_db),
) -> PredictResponse:
    """
    Generate production shipment delay prediction.
    - Resolves supplier performance, reliability, and product demand from PostgreSQL.
    - Applies registered preprocessor transformations without data leakage.
    - Executes active XGBoost classification (delay probability) and regression (delay days).
    - Categorizes delay risk: LOW (<0.30), MEDIUM (0.30 - <0.70), HIGH (>=0.70).
    """
    return PredictionService.predict_shipment(request, db)


@router.post(
    "/api/predictions/shipment-delay",
    response_model=ShipmentPredictionResult,
    status_code=status.HTTP_200_OK,
    summary="Direct feature shipment delay prediction (Day 7 legacy)",
    description="Runs XGBoost classification and regression models on directly provided feature vector.",
)
def predict_shipment_delay(
    request: ShipmentPredictionRequest,
) -> ShipmentPredictionResult:
    """
    Direct inference using pre-computed feature payload.
    """
    return PredictionService.predict_shipment_delay(request)
